#!/usr/bin/env python3
"""Generate MyGo validation directly from the exported canonical LUI contract.

--export compiles the canonical OCaml contract into runtime Go validators and a
small freshness manifest. The full export and optional oracle stay outside the
repository. Normal documentation generation and --check need only Python.
"""
import argparse
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import tempfile
import sys

sys.dont_write_bytecode = True

from mygo_contract_codegen import compile_validators
from mygo_support import support_document

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCES = ["schema/components.json", "src/lui_protocol.ml", "src/lui_protocol.mli",
           "src/lui_wire_schema.ml", "tooling/export_mygo_contract.ml"]


def source_hashes():
    # Git may check text out with CRLF on Windows; freshness tracks source
    # content rather than the host's checkout line-ending convention.
    return {name: hashlib.sha256((ROOT / name).read_bytes().replace(b"\r\n", b"\n")).hexdigest()
            for name in SOURCES}


def export_contract():
    # Dune validates content digests; identical regenerated sources can have
    # newer mtimes while the compiled objects are already current.
    subprocess.run(["opam", "exec", "--", "dune", "build", "src/lui.cmxa"], cwd=ROOT, check=True)
    with tempfile.TemporaryDirectory(prefix="lui-mygo-contract-") as directory:
        temporary = pathlib.Path(directory)
        source = temporary / "export_mygo_contract.ml"
        shutil.copy2(ROOT / "tooling/export_mygo_contract.ml", source)
        program = temporary / "export-contract"
        subprocess.run(["opam", "exec", "--", "ocamlfind", "ocamlopt", "-package",
                        "compiler-libs.common,yojson,ocaml-signal", "-linkpkg",
                        "-I", str(ROOT / "_build/default/src/.lui.objs/byte"),
                        "-I", str(ROOT / "_build/default/src/.lui.objs/native"),
                        str(ROOT / "_build/default/src/lui.cmxa"), str(source), "-o", str(program)], check=True)
        result = subprocess.run([str(program), str(ROOT / "src/lui_protocol.ml")], capture_output=True, text=True, check=True)
        contract = json.loads(result.stdout)
        contract["sourceHashes"] = source_hashes()
        return contract


def normalized_hash(data):
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def compile_go(schema, contract):
    lines = ["// Code generated by tooling/generate_mygo_schema.py; DO NOT EDIT.", "package luimygo", "", 'import "math"', "", "var wireKinds = map[string]bool{"]
    for kind, info in contract["kinds"].items():
        lines.append(f"{json.dumps(kind)}: {str(info['container']).lower()},")
    lines += ["}", "", "var wireProperties = map[string]uint8{"]
    for prop, types in contract["scalarTypes"].items():
        if not types:
            raise SystemExit("Missing canonical scalar types for " + prop)
        mask = " | ".join("scalar" + value.title() for value in sorted(types))
        lines.append(f"{json.dumps(prop)}: {mask},")
    lines += ["}"]
    for name, field in [("contractKindProperties", "properties"), ("contractKindChildren", "children"),
                        ("contractKindEvents", "events"), ("contractKindTags", "tags")]:
        lines += ["", f"var {name} = map[string]map[string]bool{{"]
        for kind, info in contract["kinds"].items():
            entries = ", ".join(json.dumps(value) + ": true" for value in info[field])
            lines.append(f"{json.dumps(kind)}: {{{entries}}},")
        lines += ["}"]
    lines += ["", "var contractTreeRows = map[string]bool{"]
    lines += [f"{json.dumps(kind)}: true," for kind, info in contract["kinds"].items() if info["treeRow"]]
    lines += ["}", "", "var contractIcons = map[string]bool{"]
    lines += [f"{json.dumps(icon)}: true," for icon in contract["icons"]]
    lines += ["}", "", "func contractPresenceSupported(kind string, properties map[string]any) bool { switch kind {"]

    def presence(rule):
        if isinstance(rule, bool):
            return str(rule).lower()
        yes, no = presence(rule["yes"]), presence(rule["no"])
        check = "contractMem(" + json.dumps(rule["property"]) + ", properties)"
        return f"(({check} && ({yes})) || (!{check} && ({no})))"

    for kind, info in contract["kinds"].items():
        lines.append(f"case {json.dumps(kind)}: return {presence(info['presence'])}")
    lines += ["}; return false }", "", compile_validators(schema, contract), ""]
    output = subprocess.run(["gofmt"], input="\n".join(lines), text=True, capture_output=True, check=True).stdout
    return output


def make_manifest(contract, output):
    return {
        "version": 1,
        "sourceHashes": contract["sourceHashes"],
        "generatedGoHash": normalized_hash(output.encode()),
        "kinds": {kind: {
            "contractHash": hashlib.sha256(json.dumps(info, sort_keys=True,
                separators=(",", ":")).encode()).hexdigest(),
            "propertyCount": len(info["properties"]),
            "childCount": len(info["children"]),
            "eventCount": len(info["events"]),
            "baseline": contract["oracle"]["nodes"][kind]["baseline"],
        } for kind, info in contract["kinds"].items()},
    }


def validate_manifest(manifest, schema):
    if manifest.get("version") != 1:
        raise SystemExit("Unsupported MyGo manifest version")
    if manifest.get("sourceHashes") != source_hashes():
        raise SystemExit("MyGo contract is stale; run python3 tooling/generate_mygo_schema.py --export")
    if set(manifest["kinds"]) != {kind["wire"] for kind in schema["nodeKinds"]}:
        raise SystemExit("MyGo manifest vocabulary differs from schema/components.json; rebuild and --export")
    target = ROOT / "platform/mygo/schema_generated.go"
    if not target.exists() or normalized_hash(target.read_bytes()) != manifest.get("generatedGoHash"):
        raise SystemExit("MyGo schema is stale; run python3 tooling/generate_mygo_schema.py --export")
    for kind, info in manifest["kinds"].items():
        if not re.fullmatch(r"[0-9a-f]{64}", info.get("contractHash", "")):
            raise SystemExit("Invalid MyGo contract hash for " + kind)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--export", action="store_true")
    parser.add_argument("--oracle-output", type=pathlib.Path,
                        help="Write the full OCaml oracle outside the repository (requires --export)")
    args = parser.parse_args()
    if args.check and args.export:
        parser.error("--check and --export cannot be combined")
    if args.oracle_output is not None:
        if not args.export:
            parser.error("--oracle-output requires --export")
        args.oracle_output = args.oracle_output.resolve()
        if args.oracle_output.is_relative_to(ROOT):
            parser.error("--oracle-output must be outside the repository")
    schema = json.loads((ROOT / "schema/components.json").read_text())
    path = ROOT / "schema/mygo-manifest.json"
    if args.export:
        contract = export_contract()
        if (set(contract["kinds"]) != {kind["wire"] for kind in schema["nodeKinds"]}
                or set(contract["properties"]) != {prop["wire"] for prop in schema["properties"]}):
            raise SystemExit("Exported MyGo vocabulary differs from schema/components.json")
        output = compile_go(schema, contract)
        manifest = make_manifest(contract, output)
        (ROOT / "platform/mygo/schema_generated.go").write_text(output)
        path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        if args.oracle_output is not None:
            args.oracle_output.write_text(json.dumps(contract, indent=2, ensure_ascii=False) + "\n")
    if not path.exists():
        raise SystemExit("Missing MyGo manifest; run tooling/generate_mygo_schema.py --export")
    manifest = json.loads(path.read_text())
    validate_manifest(manifest, schema)
    support = support_document(ROOT, manifest, schema)
    support_target = ROOT / "platform/mygo/SUPPORT.md"
    if args.check:
        if not support_target.exists() or support_target.read_text() != support:
            raise SystemExit("MyGo capabilities document is stale; run python3 tooling/generate_mygo_schema.py")
    else:
        support_target.write_text(support)


if __name__ == "__main__":
    main()
