#!/usr/bin/env python3
"""Generate MyGo wire names and scalar types from the canonical LUI sources."""
import argparse
import json
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parents[1]
schema = json.loads((root / "schema/components.json").read_text())
protocol = (root / "src/lui_protocol.ml").read_text().split("let property_value_supported property value =", 1)[1].split("let property_value_supported_for_kind", 1)[0]
scalar_types = {p["lg"]: set() for p in schema["properties"]}
for group, kind in re.findall(r"(\([^()]*\)|\b[A-Z]\w*),\s*(StringValue|IntValue|FloatValue|BoolValue)", protocol):
    for name in re.findall(r"\b[A-Z]\w*", group):
        if name in scalar_types:
            scalar_types[name].add(kind)
for name in ("PickerRequest", "PickerCompletion"):
    scalar_types[name] = {"StringValue", "IntValue"}
missing = [name for name, kinds in scalar_types.items() if not kinds]
if missing:
    raise SystemExit(f"Missing scalar types: {missing}")
mask = {"StringValue": "scalarString", "IntValue": "scalarInt", "FloatValue": "scalarFloat", "BoolValue": "scalarBool"}
lines = ["// Code generated by tooling/generate_mygo_schema.py; DO NOT EDIT.", "package luimygo", "", "var wireKinds = map[string]bool{"]
for k in schema["nodeKinds"]:
    lines.append(f'\t{json.dumps(k["wire"])}: {str(k["container"]).lower()},')
lines += ["}", "", "var wireProperties = map[string]uint8{"]
for p in schema["properties"]:
    types = " | ".join(mask[k] for k in sorted(scalar_types[p["lg"]]))
    lines.append(f'\t{json.dumps(p["wire"])}: {types},')
lines += ["}", ""]
output = subprocess.run(["gofmt"], input="\n".join(lines), text=True, capture_output=True, check=True).stdout
path = root / "platform/mygo/schema_generated.go"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit("MyGo schema is stale; run python3 tooling/generate_mygo_schema.py")
else:
    path.write_text(output)
