"""Validate exact capability sets and render the reviewable support inventory."""
import json
import re


def support_document(root, manifest, schema):
    def unique_object(pairs):
        result = {}
        for name, value in pairs:
            if name in result:
                raise SystemExit("MyGo capabilities: duplicate record " + name)
            result[name] = value
        return result

    inventory = json.loads((root / "platform/mygo/capabilities.json").read_text(),
                           object_pairs_hook=unique_object)

    def require(condition, message):
        if not condition:
            raise SystemExit("MyGo capabilities: " + message)

    def exact(actual, expected, label):
        require(len(actual) == len(set(actual)), "duplicate " + label)
        require(set(actual) == set(expected), "incomplete or unknown " + label)

    def evidence(info, label):
        refs = info.get("evidence", [])
        exception = info.get("exception")
        require(bool(refs) or exception, "missing behavior evidence for " + label)
        require(bool(info.get("route")), "missing implementation route for " + label)
        for ref in refs:
            require(isinstance(ref, str) and ":" in ref, "invalid evidence for " + label)
            filename, name = ref.split(":", 1)
            path = root / "platform/mygo" / filename
            require(path.is_file(), "missing evidence file " + ref)
            require(re.search(r"^func " + re.escape(name) + r"\(", path.read_text(), re.M),
                    "missing behavior test " + ref)
        if exception:
            require(all(exception.get(key) for key in ("scope", "reason", "source")),
                    "exception needs scope, reason and source: " + label)
            require((root / exception["source"]).is_file(), "missing exception source: " + label)

    require(inventory.get("version") == 1, "unsupported inventory version")
    exact(inventory["kinds"], manifest["kinds"], "kinds")
    exact(inventory["properties"], [prop["wire"] for prop in schema["properties"]], "property behaviors")
    events = {re.sub(r"(?<!^)(?=[A-Z])", "-", event["lg"]).lower() for event in schema["events"]}
    exact(inventory["events"], events, "event behaviors")
    for kind, info in inventory["kinds"].items():
        require(not ({"properties", "events", "children"} & info.keys()),
                "duplicated per-kind contracts: " + kind)
        require(info.get("contractHash") == manifest["kinds"][kind]["contractHash"],
                "stale or missing audited contract hash for " + kind)
        evidence(info, kind)
    for group in ("properties", "events"):
        for name, info in inventory[group].items():
            evidence(info, name)

    def cell(text):
        return str(text).replace("|", "\\|").replace("\n", " ")

    def refs(info):
        return ", ".join("[" + ref.split(":", 1)[1] + "](" + ref.split(":", 1)[0] + ")"
                         for ref in info["evidence"])

    lines = ["# MyGo component support", "",
             "<!-- Generated by tooling/generate_mygo_schema.py; edit capabilities.json. -->", "",
             inventory["scope"], "",
             "This inventory records implementation routes and behavioral test references. "
             "It does not establish live desktop qualification; see the host table below. "
             "Per-kind hashes bind reviewed behavior to the canonical OCaml contracts. "
             "Feature exceptions apply only to the specified values, never to an entire component.", "",
             "## Desktop qualification", "",
             "| Host | Automated checks | Live checks |", "| --- | --- | --- |"]
    for host, info in inventory["qualification"].items():
        lines.append("| " + " | ".join(map(cell, [host, info["automated"], info["live"]])) + " |")
    lines += ["", "## Components", "",
              "Contract counts and hashes come from the canonical OCaml export in "
              "[the manifest](../../schema/mygo-manifest.json). Shared property behavior is listed below.", "",
              "| Kind | Built-in route | Properties | Allowed child kinds | Events | Behavior evidence |",
              "| --- | --- | --- | --- | --- | --- |"]
    for kind, info in inventory["kinds"].items():
        lines.append("| " + " | ".join(map(cell, ["`" + kind + "`", info["route"],
            manifest["kinds"][kind]["propertyCount"], manifest["kinds"][kind]["childCount"], manifest["kinds"][kind]["eventCount"], refs(info)])) + " |")
    lines += ["", "## Properties and feature exceptions", "",
              "| Property | Implementation | Exception | Behavior evidence |",
              "| --- | --- | --- | --- |"]
    for name, info in inventory["properties"].items():
        exception = info.get("exception")
        detail = "—"
        if exception:
            detail = (exception["scope"] + ": " + exception["reason"] +
                      " ([contract](../../" + exception["source"] + "))")
        lines.append("| " + " | ".join(map(cell, ["`" + name + "`", info["route"], detail, refs(info)])) + " |")
    lines += ["", "## Event bridge", "",
              "All event families round-trip through the real OCaml Components application. "
              "Payload checks include Unicode, embedded NUL, large integer tokens, "
              "pointer metadata, empty visible ranges and scroll outcomes.", "",
              "| Event | Route | Behavior evidence |", "| --- | --- | --- |"]
    for name, info in inventory["events"].items():
        lines.append("| " + " | ".join(map(cell, ["`" + name + "`", info["route"], refs(info)])) + " |")
    lines += ["", "Regenerate with `python3 tooling/generate_mygo_schema.py`; "
              "CI checks exact sets, evidence references, exception sources and this document.", ""]
    return "\n".join(lines)
